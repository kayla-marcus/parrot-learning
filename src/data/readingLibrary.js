const formatChoice = (text) => text

const formatReadingPrompt = (promptText, story) => {
  const prompt = promptText.replace(/\?$/, '').replace(' from this story', '')
  return `${prompt}, in the story, “${story.title}”?`
}

const makeQuestions = (story, storyIndex, allStories) => {
  const questionData = {
    'identify-facts': [null, []],
    'key-details': [story.detail, story.detailDistractors],
    'text-evidence': [story.evidence, story.evidenceDistractors],
    'match-detail': [story.match, story.matchDistractors],
    'main-idea': [story.mainIdea, story.mainIdeaDistractors],
    'best-summary': [story.summary, story.summaryDistractors],
    'support-main-idea': [story.support, story.supportDistractors],
    'compare-main-ideas': [story.compare, story.compareDistractors],
  }

  return Object.entries(questionData).flatMap(([skill, [answer]]) => {
    if (skill === 'identify-facts') {
      return questionPrompts[skill].map((promptText, questionIndex) => {
        const factNumber = (questionIndex % 5) + 1
        const factAnswer = story[`fact${factNumber}Correct`]
        const factDistractors = [1, 2, 3].map((incorrectNumber) =>
          story[`fact${factNumber}Incorrect${incorrectNumber}`],
        )
        const formattedAnswer = formatChoice(factAnswer)
        const formattedDistractors = factDistractors.map((distractor) =>
          formatChoice(distractor),
        )

        return question(
          skill,
          formatReadingPrompt(promptText, story),
          formattedAnswer,
          formattedDistractors,
          (storyIndex + questionIndex) % 4,
        )
      })
    }

    const distractorPool = [...new Set(
      allStories.flatMap((candidate) => {
        const [, candidateDistractors] = {
          'identify-facts': [candidate.fact, candidate.factDistractors],
          'key-details': [candidate.detail, candidate.detailDistractors],
          'text-evidence': [candidate.evidence, candidate.evidenceDistractors],
          'match-detail': [candidate.match, candidate.matchDistractors],
          'main-idea': [candidate.mainIdea, candidate.mainIdeaDistractors],
          'best-summary': [candidate.summary, candidate.summaryDistractors],
          'support-main-idea': [candidate.support, candidate.supportDistractors],
          'compare-main-ideas': [candidate.compare, candidate.compareDistractors],
        }[skill]
        return candidateDistractors
      }),
    )].filter((distractor) => distractor !== answer)

    return questionPrompts[skill].map((promptText, questionIndex) => {
      const offset = (storyIndex * 7 + questionIndex * 3) % distractorPool.length
      const distractors = Array.from({ length: 3 }, (_, index) =>
        distractorPool[(offset + index) % distractorPool.length],
      )
      const formattedAnswer = formatChoice(answer)
      const formattedDistractors = distractors.map((distractor) =>
        formatChoice(distractor),
      )

      const readingPrompt = skill === 'text-evidence'
        ? `Which evidence best supports the idea that ${story.evidenceIdea}, in the story, “${story.title}”?`
        : formatReadingPrompt(
            `${promptText}${skill === 'main-idea' ? ` (about ${story.topic})` : ''}${skill === 'support-main-idea' ? ` (${story.mainIdea.toLowerCase()})` : ''}`,
            story,
          )

      return question(
        skill,
        readingPrompt,
        formattedAnswer,
        formattedDistractors,
        (storyIndex + questionIndex) % 4,
      )
    })
  })
}

