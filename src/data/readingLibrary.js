const question = (skill, prompt, answer, distractors, correctPosition) => {
  const options = Array(4)
  options[correctPosition] = answer
  distractors.forEach((distractor, index) => {
    options[(correctPosition + index + 1) % options.length] = distractor
  })

  return {
  skill,
  type: 'radio',
  prompt,
    options,
  answer,
  }
}

